"""
Build compose.override.yaml from an app spec's volume and network overrides.

Compose merges service `volumes` by mount target and replaces `networks` without keeping `default`,
so a plain override would leave the original mount in place and detach services from the default
network. Instead, changed services get their full list rewritten with the `!override` tag
(docker compose >= 2.24.4).
"""
from typing import TYPE_CHECKING, Any

import re

import yaml

from mc.util.yaml_util import LiteralDumper

if TYPE_CHECKING:
    from mc.plugin.apps.apps_helper import AppSpec


class OverrideList(list):
    """Dumped with the `!override` tag: replaces the base list instead of merging."""


class OverrideDict(dict):
    """Dumped with the `!override` tag: replaces the base mapping instead of merging."""


class ComposeDumper(LiteralDumper):
    pass


ComposeDumper.add_representer(OverrideList, lambda d, v: d.represent_sequence("!override", list(v)))
ComposeDumper.add_representer(OverrideDict, lambda d, v: d.represent_mapping("!override", dict(v)))


GENERATED_HEADER = "# Generated by mc from the app spec. Changes here are overwritten on save.\n"


def dump_override(override: dict[str, Any]) -> str:
    return GENERATED_HEADER + yaml.dump(override, Dumper=ComposeDumper, default_flow_style=False, sort_keys=False)


def parse_mount(entry: Any) -> tuple[str | None, str | None, bool]:
    """(source, target, read_only) of a service volume entry, short or long syntax."""
    if isinstance(entry, dict):
        return entry.get("source"), entry.get("target"), bool(entry.get("read_only"))
    if isinstance(entry, str):
        parts = entry.split(":")
        if len(parts) == 1:  # anonymous volume: just the target
            return None, parts[0], False
        read_only = len(parts) > 2 and "ro" in parts[2].split(",")
        return parts[0], parts[1], read_only
    return None, None, False


def _service_networks(service: dict[str, Any]) -> dict[str, Any]:
    """Service networks as a mapping. A service without networks is on `default`."""
    networks = service.get("networks")
    if networks is None:
        return {"default": {}}
    if isinstance(networks, list):
        return {name: {} for name in networks}
    if isinstance(networks, dict):
        return {name: (cfg if cfg is not None else {}) for name, cfg in networks.items()}
    return {}


def _spec_service_networks(spec: "AppSpec", service: dict[str, Any]) -> dict[str, Any]:
    """Service networks once compose.override.yaml is applied: its own plus every spec network."""
    merged = _service_networks(service)
    for net in spec.networks or []:
        merged.setdefault(net.network_name, {})
    return merged


def build_override(spec: "AppSpec", stack: dict[str, Any]) -> tuple[dict[str, Any], list[str]]:
    """
    :param spec: the app spec with volume / network overrides
    :param stack: the parsed main compose file
    :return: (override compose dict, warnings)
    """
    services: dict[str, Any] = stack.get("services") or {}
    warnings: list[str] = []
    out_services: dict[str, dict[str, Any]] = {}
    out_volumes: dict[str, Any] = {}
    out_networks: dict[str, Any] = {}

    # Volumes: replace every mount of the named volume with the spec's mount
    volume_lists = {name: list((svc or {}).get("volumes") or []) for name, svc in services.items()}
    changed: set[str] = set()
    for vol in spec.volumes or []:
        mount: dict[str, Any] = {
            "type": "bind" if vol.bind else "volume",
            "source": vol.host_path if vol.bind else vol.volume_name,
            "target": vol.container_path,
        }
        if vol.bind:
            mount["bind"] = {"create_host_path": True}

        used = False
        for service_name, entries in volume_lists.items():
            for i, entry in enumerate(entries):
                source, _, read_only = parse_mount(entry)
                if source == vol.volume_name:
                    entries[i] = {**mount, **({"read_only": True} if read_only else {})}
                    changed.add(service_name)
                    used = True

        if not used:
            if len(services) == 1:
                # only one place it can go
                service_name = next(iter(services))
                volume_lists[service_name].append(dict(mount))
                changed.add(service_name)
            else:
                warnings.append(
                    f"Volume '{vol.volume_name}' isn't mounted by any service, so it was skipped. "
                    f"Mount it in compose.yaml first."
                )
                continue

        if not vol.bind:
            out_volumes[vol.volume_name] = {}

    for service_name in sorted(changed):
        out_services.setdefault(service_name, {})["volumes"] = OverrideList(volume_lists[service_name])

    # Networks: every service joins every spec network
    for net in spec.networks or []:
        out_networks[net.network_name] = OverrideDict(external=True) if net.external else {}

    if spec.networks:
        for service_name, svc in services.items():
            svc = svc or {}
            if svc.get("network_mode"):
                warnings.append(
                    f"Service '{service_name}' uses network_mode '{svc['network_mode']}', so it can't join networks."
                )
                continue
            current = _service_networks(svc)
            merged = _spec_service_networks(spec, svc)
            if merged != current or svc.get("networks") is None:
                out_services.setdefault(service_name, {})["networks"] = OverrideDict(merged)

    override: dict[str, Any] = {"services": out_services}
    if out_volumes:
        override["volumes"] = out_volumes
    if out_networks:
        override["networks"] = out_networks
    return override, warnings


# Traefik runs on this external network, with these entrypoints and certificate resolver
TRAEFIK_NETWORK_NAME = "traefik"
TRAEFIK_HTTP_ENTRYPOINT = "web"
TRAEFIK_HTTPS_ENTRYPOINT = "websecure"
TRAEFIK_CERT_RESOLVER = "le"


def traefik_key(app_id: str, service_name: str, port: int) -> str:
    """Traefik router / service name. Dots would split the label path, so they become '-'."""
    return re.sub(r"[^a-zA-Z0-9_-]", "-", f"{app_id}-{service_name}-{port}")


def build_traefik_override(spec: "AppSpec", stack: dict[str, Any]) -> tuple[dict[str, Any], list[str]]:
    """
    compose.traefik.yaml: traefik labels for each route, and the routed services join the traefik network.

    Applied after compose.override.yaml, so service networks are rewritten (`!override`) with the
    spec networks included.

    :param spec: the app spec with routes
    :param stack: the parsed main compose file
    :return: (override compose dict, warnings)
    """
    services: dict[str, Any] = stack.get("services") or {}
    warnings: list[str] = []
    labels_by_service: dict[str, dict[str, str]] = {}

    for route in spec.routing or []:
        svc = services.get(route.service_name)
        if route.service_name not in services:
            warnings.append(f"Route to '{route.service_name}' skipped: no such service in compose.yaml.")
            continue
        if (svc or {}).get("network_mode"):
            warnings.append(
                f"Route to '{route.service_name}' skipped: the service uses network_mode, so traefik can't reach it."
            )
            continue

        key = traefik_key(spec.id, route.service_name, route.container_port)
        rule = " || ".join(f"Host(`{d}`)" for d in route.domain_names)
        labels = labels_by_service.setdefault(route.service_name, {
            "traefik.enable": "true",
            "traefik.docker.network": TRAEFIK_NETWORK_NAME,
        })
        labels[f"traefik.http.services.{key}.loadbalancer.server.port"] = str(route.container_port)
        if route.mode in ("http", "http+https"):
            router = f"traefik.http.routers.{key}-http"
            labels[f"{router}.rule"] = rule
            labels[f"{router}.entrypoints"] = TRAEFIK_HTTP_ENTRYPOINT
            labels[f"{router}.service"] = key
        if route.mode in ("https", "http+https"):
            router = f"traefik.http.routers.{key}-https"
            labels[f"{router}.rule"] = rule
            labels[f"{router}.entrypoints"] = TRAEFIK_HTTPS_ENTRYPOINT
            labels[f"{router}.service"] = key
            labels[f"{router}.tls"] = "true"
            labels[f"{router}.tls.certresolver"] = TRAEFIK_CERT_RESOLVER

    out_services: dict[str, Any] = {}
    for service_name, labels in labels_by_service.items():
        networks = _spec_service_networks(spec, services[service_name] or {})
        networks.setdefault(TRAEFIK_NETWORK_NAME, {})
        # labels merge with the base file's labels; networks must list everything (see module docstring)
        out_services[service_name] = {"labels": labels, "networks": OverrideDict(networks)}

    override: dict[str, Any] = {"services": out_services}
    if out_services:
        override["networks"] = {TRAEFIK_NETWORK_NAME: OverrideDict(external=True)}
    return override, warnings
