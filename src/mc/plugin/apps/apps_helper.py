# App ids double as compose project names: lowercase letters, digits, "-" and "_".
APP_ID_PATTERN = re.compile(r"^[a-z0-9][a-z0-9_-]{0,62}$")
RESERVED_APP_IDS = {"new"}

# docker compose actions an app can run
AppAction = Literal["up", "down", "stop", "restart"]

DEFAULT_STACKFILE = "compose.yaml"
# generated by AppSpec.compile(), applied on top of the main stackfile when present
OVERRIDE_STACKFILES = ["compose.override.yaml", "compose.traefik.yaml"]


def validate_app_id(app_id: str) -> str:
    if not APP_ID_PATTERN.match(app_id) or app_id in RESERVED_APP_IDS:
        raise ValueError(
            f"Invalid app id '{app_id}'. Use lowercase letters, digits, '-' and '_' (max 63 chars)."
        )
    return app_id


def get_app_dir(app_name: str) -> str:
    """Project dir of an app (compose files, runtime data)."""
    return os.path.join(MC_HOME, "apps", app_name)


def get_appspec_dir() -> str:
    """Directory holding all app specs."""
    return os.path.join(MC_CONFIG_DIR, "apps")


def get_appspec_path(app_id: str) -> str:
    return os.path.join(get_appspec_dir(), f"{validate_app_id(app_id)}.yaml")


def write_file_atomic(path: str, contents: str) -> None:
    """Write via a temp file in the same dir, then rename over the target."""
    directory = os.path.dirname(path)
    os.makedirs(directory, exist_ok=True)
    fd, tmp_path = tempfile.mkstemp(dir=directory, prefix=".tmp-")
    try:
        with os.fdopen(fd, "w") as f:
            f.write(contents)
        os.replace(tmp_path, path)
    except Exception:
        if os.path.exists(tmp_path):
            os.remove(tmp_path)
        raise


def compose_declared_names(stack: dict[str, Any] | None) -> tuple[list[str], list[str]]:
    """Top-level volume and network names declared in a parsed compose file."""
    if not isinstance(stack, dict):
        return [], []
    names = []
    for key in ("volumes", "networks"):
        section = stack.get(key)
        names.append(sorted(section.keys()) if isinstance(section, dict) else [])
    return names[0], names[1]


def _container_port(entry: Any) -> int | None:
    """Container port of a `ports` / `expose` entry: "8080:80", "127.0.0.1:80:80/tcp", 80, {target: 80}."""
    if isinstance(entry, dict):
        entry = entry.get("target")
    if isinstance(entry, int):
        return entry
    if isinstance(entry, str):
        port = entry.rsplit(":", 1)[-1].split("/", 1)[0].split("-", 1)[0]
        return int(port) if port.isdigit() else None
    return None


def compose_service_ports(stack: dict[str, Any] | None) -> dict[str, list[int]]:
    """Service names of a parsed compose file, with the container ports they publish or expose."""
    if not isinstance(stack, dict) or not isinstance(stack.get("services"), dict):
        return {}
    result = {}
    for name, svc in stack["services"].items():
        svc = svc if isinstance(svc, dict) else {}
        ports = []
        for key in ("ports", "expose"):
            for entry in svc.get(key) or []:
                port = _container_port(entry)
                if port and port not in ports:
                    ports.append(port)
        result[str(name)] = sorted(ports)
    return result


def validate_compose_stackfile(contents: str) -> dict[str, Any]:
    """Check that contents is a YAML mapping with a non-empty 'services' section."""
    try:
        data = yaml.safe_load(contents)
    except yaml.YAMLError as e:
        raise ValueError(f"Invalid YAML: {e}") from e
    if not isinstance(data, dict):
        raise ValueError("Compose file must be a YAML mapping")
    services = data.get("services")
    if not isinstance(services, dict) or not services:
        raise ValueError("Compose file must define at least one service under 'services'")
    return data

# Docker volume / network names
RESOURCE_NAME_PATTERN = re.compile(r"^[a-zA-Z0-9][a-zA-Z0-9_.-]*$")


def _validate_resource_name(kind: str, name: str) -> str:
    name = name.strip()
    if not RESOURCE_NAME_PATTERN.match(name):
        raise ValueError(f"Invalid {kind} name '{name}'. Use letters, digits, '_', '.' and '-'.")
    return name


class AppVolumeSpec(pydantic.BaseModel):
    volume_name: str
    container_path: str
    bind: bool = False
    host_path: str | None = None # only if bind == True

    @pydantic.field_validator("volume_name")
    @classmethod
    def _check_volume_name(cls, v: str) -> str:
        return _validate_resource_name("volume", v)

    @pydantic.field_validator("container_path")
    @classmethod
    def _check_container_path(cls, v: str) -> str:
        v = v.strip()
        if not v.startswith("/"):
            raise ValueError("Container path must be absolute (start with '/')")
        return v

    @pydantic.model_validator(mode="after")
    def _check_host_path(self) -> "AppVolumeSpec":
        if not self.bind:
            self.host_path = None
        elif not (self.host_path or "").strip():
            raise ValueError(f"Volume '{self.volume_name}': host path is required for bind mounts")
        else:
            self.host_path = self.host_path.strip()
        return self


class AppNetworkSpec(pydantic.BaseModel):
    network_name: str
    external: bool = False

    @pydantic.field_validator("network_name")
    @classmethod
    def _check_network_name(cls, v: str) -> str:
        return _validate_resource_name("network", v)


# Compose service names
SERVICE_NAME_PATTERN = re.compile(r"^[a-zA-Z0-9][a-zA-Z0-9_.-]*$")
# Hostnames for traefik Host() rules, no wildcards
DOMAIN_NAME_PATTERN = re.compile(r"^(?=.{1,253}$)([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?)(\.[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?)*$")


class AppRoutingSpec(pydantic.BaseModel):
    service_name: str
    container_port: int = pydantic.Field(ge=1, le=65535)
    mode: Literal["http", "https", "http+https"] = "http"
    domain_names: list[str] = pydantic.Field(default_factory=list)

    @pydantic.field_validator("service_name")
    @classmethod
    def _check_service_name(cls, v: str) -> str:
        v = v.strip()
        if not SERVICE_NAME_PATTERN.match(v):
            raise ValueError(f"Invalid service name '{v}'. Use letters, digits, '_', '.' and '-'.")
        return v

    @pydantic.field_validator("domain_names")
    @classmethod
    def _check_domain_names(cls, v: list[str]) -> list[str]:
        names = []
        for d in v:
            d = d.strip().lower().rstrip(".")
            if not d:
                continue
            if not DOMAIN_NAME_PATTERN.match(d):
                raise ValueError(f"Invalid domain name '{d}'")
            if d not in names:
                names.append(d)
        if not names:
            raise ValueError("At least one domain name is required")
        return names


# Environment variable names, and the ones mc sets for docker compose itself
ENV_NAME_PATTERN = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
RESERVED_ENV_NAMES = {"DOCKER_HOST", "COMPOSE_PROJECT_DIRECTORY", "COMPOSE_PROJECT_NAME"}


def _env_value(v: Any) -> str:
    if v is None:
        return ""
    if isinstance(v, bool):
        return str(v).lower()
    return str(v)


class AppSpec(pydantic.BaseModel):
    id: str
    type: Literal["container", "compose"]
    title: str | None = None
    description: str | None = None
    image: str | None = None # only container
    stackfile: str | None = None # only compose
    volumes: list[AppVolumeSpec] = pydantic.Field(default_factory=list) # overrides
    networks: list[AppNetworkSpec] = pydantic.Field(default_factory=list) # overrides
    # injected into the docker compose subprocess (variable interpolation), never written to compose files
    environment: dict[str, str] = pydantic.Field(default_factory=dict)
    # routing options
    routing: list[AppRoutingSpec] = pydantic.Field(default_factory=list)


    @pydantic.field_validator("environment", mode="before")
    @classmethod
    def _coerce_environment(cls, v: Any) -> Any:
        # hand-edited specs may hold numbers, booleans or empty values
        if isinstance(v, dict):
            return {str(k).strip(): _env_value(val) for k, val in v.items()}
        return v

    @pydantic.field_validator("environment")
    @classmethod
    def _check_environment(cls, v: dict[str, str] | None) -> dict[str, str] | None:
        for name in v or {}:
            if not ENV_NAME_PATTERN.match(name):
                raise ValueError(f"Invalid variable name '{name}'. Use letters, digits and '_', not starting with a digit.")
            if name in RESERVED_ENV_NAMES:
                raise ValueError(f"Variable '{name}' is set by mc and can't be overridden.")
        return v

    @pydantic.model_validator(mode="after")
    def _check_unique_names(self) -> "AppSpec":
        for kind, names in (
            ("volume", [v.volume_name for v in self.volumes or []]),
            ("network", [n.network_name for n in self.networks or []]),
        ):
            dupes = sorted({n for n in names if names.count(n) > 1})
            if dupes:
                raise ValueError(f"Duplicate {kind} names: {', '.join(dupes)}")
        targets = [f"{r.service_name}:{r.container_port}" for r in self.routing]
        dupes = sorted({t for t in targets if targets.count(t) > 1})
        if dupes:
            raise ValueError(f"Duplicate routes to {', '.join(dupes)}. Put all domains of a port in one route.")
        return self

    @property
    def project_dir(self) -> str:
        return get_app_dir(self.id)

    @property
    def real_project_dir(self) -> str:
        return str(get_mc_real_path(self.project_dir))

    @property
    def stackfile_path(self) -> str:
        if self.stackfile is None:
            raise RuntimeError("No stackfile specified")
        return os.path.join(get_app_dir(self.id), self.stackfile)

    def read_stackfile(self) -> str:
        with open(self.stackfile_path, "r") as f:
            return f.read()

    def write_stackfile(self, contents: str) -> None:
        write_file_atomic(self.stackfile_path, contents)

    @property
    def override_path(self) -> str:
        return os.path.join(get_app_dir(self.id), "compose.override.yaml")

    @property
    def traefik_override_path(self) -> str:
        return os.path.join(get_app_dir(self.id), "compose.traefik.yaml")

    def compile(self, vars: dict[str, str] | None = None) -> list[str]:
        """
        Generate compose.override.yaml (volume / network overrides) and compose.traefik.yaml (routing).

        :return: warnings, e.g. overrides that couldn't be applied
        """
        stack = self.parse_stackfile(self.read_stackfile()) or {}
        override, warnings = build_override(self, stack)
        write_file_atomic(self.override_path, dump_override(override))

        traefik, traefik_warnings = build_traefik_override(self, stack)
        write_file_atomic(self.traefik_override_path, dump_override(traefik))
        return warnings + traefik_warnings

    def stackfile_paths(self) -> list[str]:
        """Main stackfile plus the generated override files that exist."""
        paths = [self.stackfile_path]
        for name in OVERRIDE_STACKFILES:
            path = os.path.join(get_app_dir(self.id), name)
            if os.path.isfile(path):
                paths.append(path)
        return paths

    def compose_runner(self, global_args: list[str] | None = None) -> LocalDockerComposeStackRunner:
        if self.type != "compose":
            raise ValueError("Only compose apps have a compose runner")
        if not self.stackfile:
            raise ValueError("Compose project must have a stackfile")
        return LocalDockerComposeStackRunner(
            self.id,
            self.real_project_dir,
            stackfiles=self.stackfile_paths(),
            global_args=global_args,
            env=self.environment,
        )

    def action_cmd(self, action: AppAction, global_args: list[str] | None = None) -> tuple[list[str], dict[str, str]]:
        """(command, env) of a docker compose action, to run as a subprocess."""
        runner = self.compose_runner(global_args=global_args)
        if action == "up":
            # always detach: an attached `up` never exits
            return runner.up_cmd(DockerComposeUpArgs(detach=True, remove_orphans=True, yes=True, no_color=True))
        if action == "down":
            return runner.compose_cmd("down", **DockerComposeDownArgs().model_dump())
        if action == "stop":
            return runner.compose_cmd("stop", **DockerComposeStopArgs().model_dump())
        if action == "restart":
            return runner.compose_cmd("restart", **DockerComposeArgs().model_dump())
        raise ValueError(f"Unknown action '{action}'")

    def run(self) -> None:
        if self.type == "compose":
            runner = self.compose_runner()
            runner.up(DockerComposeUpArgs(
                remove_orphans=True,
                quiet_pull=True,
                yes=True,
                no_color=True,
            ))
        else:
            raise NotImplementedError()

    @staticmethod
    def parse_stackfile(contents: str) -> dict[str, Any]:
        return yaml.safe_load(contents)

    @staticmethod
    def create_from_string(name: str, contents: str, **kwargs) -> "AppSpec":
        """Create a compose app from a compose.yaml string. Writes the stackfile and saves the spec."""
        validate_app_id(name)
        validate_compose_stackfile(contents)
        spec = AppSpec(id=name, type="compose", stackfile=DEFAULT_STACKFILE, **kwargs)
        spec.write_stackfile(contents)
        save_app_spec(spec)
        return spec

    @staticmethod
    def create_from_bundle(name: str, fileobj: BinaryIO, **kwargs) -> "AppSpec":
        """Create a compose app from a bundle (tar archive). Extracts it into the app folder and saves the spec."""
        validate_app_id(name)
        with ExtractedBundle(fileobj) as bundle:
            validate_compose_stackfile(bundle.read_stackfile())
            spec = AppSpec(id=name, type="compose", stackfile=bundle.stackfile, **kwargs)
            bundle.install(spec.project_dir)
        save_app_spec(spec)
        return spec

    def update_from_bundle(self, fileobj: BinaryIO) -> "AppSpec":
        """
        Extract a bundle over the app folder and save the spec, pointing at the bundle's compose file.
        Files that aren't in the bundle (e.g. bind mount data) are kept. Returns the updated spec.
        """
        if self.type != "compose":
            raise ValueError("Only compose apps can be updated from a bundle")
        with ExtractedBundle(fileobj) as bundle:
            validate_compose_stackfile(bundle.read_stackfile())
            spec = AppSpec.model_validate({**self.model_dump(), "stackfile": bundle.stackfile})
            bundle.install(spec.project_dir)
        save_app_spec(spec)
        return spec

    @staticmethod
    def create_from_template(template: AppTemplate) -> "AppSpec":
        raise NotImplementedError()


def app_spec_exists(app_id: str) -> bool:
    return os.path.isfile(get_appspec_path(app_id))


def load_app_spec(app_id: str) -> AppSpec:
    path = get_appspec_path(app_id)
    if not os.path.isfile(path):
        raise FileNotFoundError(f"App spec not found: {app_id}")
    with open(path) as f:
        data = yaml.safe_load(f) or {}
    data["id"] = app_id  # the file name is the source of truth
    return AppSpec.model_validate(data)


def save_app_spec(spec: AppSpec) -> None:
    data = spec.model_dump(mode="json", exclude_none=True)
    contents = yaml.dump(data, Dumper=yaml.SafeDumper, default_flow_style=False, sort_keys=False)
    write_file_atomic(get_appspec_path(spec.id), contents)


def list_app_specs() -> list[AppSpec]:
    spec_dir = get_appspec_dir()
    if not os.path.isdir(spec_dir):
        return []
    specs = []
    for name in sorted(os.listdir(spec_dir)):
        if not name.endswith(".yaml"):
            continue
        app_id = name[: -len(".yaml")]
        try:
            specs.append(load_app_spec(app_id))
        except Exception as e:
            print(f"Skipping invalid app spec {name}: {e}")
    return specs